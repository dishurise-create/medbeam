import Foundation
import MapKit

/// A specific medication product (drug + strength + form), normalized by RxNorm.
struct Medication: Identifiable, Hashable, Codable {
    let rxcui: String
    /// Full RxNorm name, e.g. "24 HR amphetamine aspartate 5 MG / ... Extended Release Oral Capsule"
    let name: String
    /// Friendlier name when RxNorm has one, e.g. "Adderall XR 20 MG 24 HR Extended Release Oral Capsule"
    let displayName: String
    /// RxNorm term type: SBD = branded drug, SCD = generic drug
    let termType: String

    var id: String { rxcui }
    var isBrand: Bool { termType == "SBD" }

    /// Lower = more commonly picked up at a retail pharmacy. Used to order search results.
    var formRank: Int {
        let n = name.lowercased()
        if n.contains("inject") || n.contains("transdermal") || n.contains("implant") || n.contains("irrigation") { return 3 }
        if n.contains("oral solution") || n.contains("oral suspension") || n.contains("syrup") { return 2 }
        if n.contains("extended release") || n.contains("delayed release") || n.contains("chewable") || n.contains("disintegrating") { return 1 }
        return 0
    }

    /// Shorter name for titles, e.g. "Adderall XR 20 mg ER capsule"
    var shortName: String {
        // Drop duration prefixes like "24 HR" / "8 HR" anywhere in the name
        var text = displayName
            .replacingOccurrences(of: #"\b\d+ HR\b ?"#, with: "", options: .regularExpression)
            // "amoxicillin (as amoxicillin trihydrate) 500 MG" → "amoxicillin 500 MG"
            .replacingOccurrences(of: #" \(as [^)]*\)"#, with: "", options: .regularExpression)
        let replacements = [
            ("Extended Release", "ER"), ("Delayed Release", "DR"),
            ("Oral Capsule", "capsule"), ("Oral Tablet", "tablet"), ("Oral Solution", "solution"),
            ("Oral Suspension", "suspension"), (" MG", " mg"), (" MCG", " mcg"), (" ML", " mL"),
        ]
        for (long, short) in replacements { text = text.replacingOccurrences(of: long, with: short) }
        return text
    }
}

/// Extra RxNorm info used to match a medication against FDA shortage records.
struct MedicationDetails {
    let medication: Medication
    /// Ingredient names, e.g. ["amphetamine", "dextroamphetamine"]
    let ingredients: [String]
    /// RxCUIs of the medication and its generic equivalents
    let relatedRxcuis: [String]
    /// Generic (SCD) name — used to read strength and dosage form
    let genericName: String

    static func basic(_ med: Medication) -> MedicationDetails {
        MedicationDetails(medication: med, ingredients: [], relatedRxcuis: [med.rxcui], genericName: med.name)
    }
}

struct Pharmacy: Identifiable, Hashable {
    /// Stable ID built from name + rounded location, so reports match across searches.
    let id: String
    let name: String
    let address: String
    let phone: String?
    let url: URL?
    let coordinate: CLLocationCoordinate2D
    let distanceMiles: Double
    let mapItem: MKMapItem

    static func == (lhs: Pharmacy, rhs: Pharmacy) -> Bool { lhs.id == rhs.id }
    func hash(into hasher: inout Hasher) { hasher.combine(id) }
}

/// One anonymous "did they have it?" answer. Contains no personal information.
struct AvailabilityReport: Codable, Identifiable {
    enum Result: String, Codable {
        case inStock
        case outOfStock
    }

    let id: UUID
    let rxcui: String
    let pharmacyID: String
    let latitude: Double
    let longitude: Double
    let result: Result
    let timestamp: Date
    /// True for demo data generated by the app. Always shown with a "Simulated" label.
    let isSimulated: Bool
    /// Names kept only on this device so the History tab can show them.
    var medicationName: String? = nil
    var pharmacyName: String? = nil

    var location: CLLocation { CLLocation(latitude: latitude, longitude: longitude) }
}

// MARK: - FDA shortage status

struct ManufacturerSupply: Identifiable {
    enum Category: String {
        case available = "Available"
        case limited = "Limited"
        case unavailable = "Unavailable"
        case unknown = "Not reported"
    }

    let company: String
    let category: Category
    let rawAvailability: String?
    let updateDate: Date?

    var id: String { company }
}

struct ShortageStatus {
    enum Level {
        /// No matching record in the FDA shortage database
        case none
        /// FDA lists a current shortage
        case active
        /// FDA lists the shortage as resolved
        case resolved
        /// FDA lists the product as being discontinued
        case discontinuing
        /// We couldn't reach the FDA database
        case unknown

        var headline: String {
            switch self {
            case .none: return "No official FDA shortage"
            case .active: return "Official FDA shortage"
            case .resolved: return "FDA shortage resolved"
            case .discontinuing: return "Being discontinued (FDA)"
            case .unknown: return "FDA status unavailable"
            }
        }
    }

    let level: Level
    let manufacturers: [ManufacturerSupply]
    let initialPostingDate: Date?
    let lastUpdated: Date?
    let fetchedAt: Date

    /// 0...1 national supply signal used as the starting point (prior) for every pharmacy.
    var nationalSupplyScore: Double {
        switch level {
        case .none: return 0.85
        case .resolved: return 0.80
        case .discontinuing: return 0.55
        case .unknown: return 0.60
        case .active:
            let known = manufacturers.filter { $0.category != .unknown }
            guard !known.isEmpty else { return 0.45 }
            let supply = known.reduce(0.0) { total, m in
                switch m.category {
                case .available: return total + 1.0
                case .limited: return total + 0.5
                default: return total
                }
            }
            let fraction = supply / Double(known.count)
            return 0.20 + 0.60 * fraction
        }
    }

    var headline: String { level.headline }

    static func unknown() -> ShortageStatus {
        ShortageStatus(level: .unknown, manufacturers: [], initialPostingDate: nil, lastUpdated: nil, fetchedAt: .now)
    }
}
